  const OCR_FIX = [[/汗$/, '汁'], [/汗(?=[\s、])/g, '汁'], [/飯$/, '飯'], [/姜/g, '姜'], [/ロ/g, 'ロ']];
  function toHalf(s) { return s.replace(/[０-９Ａ-Ｚａ-ｚ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0)).replace(/\u3000/g, ' '); }
  // 1料理名 → {dish, fromName:[], typical:[], matched:'辞書キー' }
  function analyzeDish(name) {
    const n = toHalf(name).replace(/[\s・、,（）()「」【】]/g, '');
    const fromName = [];
    // 料理名中の材料語 (長い語優先、重なりは除外)
    const used = new Array(n.length).fill(false);
    for (const k of ingKeys) {
      let idx = n.indexOf(k);
      while (idx >= 0) {
        if (!used.slice(idx, idx + k.length).some(Boolean)) {
          used.fill(true, idx, idx + k.length);
          if (!fromName.includes(ING[k])) fromName.push(ING[k]);
        }
        idx = n.indexOf(k, idx + 1);
      }
    }
    // 辞書照合: 完全一致 > 料理名に辞書キーを含む (最長)
    let matched = DISH[n] ? n : dishKeys.find(k => n.includes(k)) || '';
    // 料理名に含まれていた材料と辞書キーが重なる場合でも辞書は使う
    const typical = matched ? DISH[matched].filter(x => !fromName.includes(x)) : [];
    // 「卵の味噌汁」等: 名前で具が明示されたら、辞書の代表的な具(豆腐/わかめ)は「候補」に下げる
    let optional = [];
    if (matched && /(汁|スープ)$/.test(matched) && fromName.some(x => !['味噌'].includes(x))) {
      optional = typical.filter(x => ['豆腐', 'わかめ', '油揚げ'].includes(x));
    }
    return { dish: name.trim(), fromName, typical: typical.filter(x => !optional.includes(x)), optional, matched };
  }
  function findDishes(text) {
    const out = [];
    for (let line of text.split(/\r?\n/)) {
      line = toHalf(line).replace(/^[\s\-・●○◎■□*]+/, '').trim();
      // Tesseract(jpn) は文字間に空白を入れるので、日本語文字間の単一空白は詰める
      line = line.replace(/([^\x00-\x7F]) (?=[^\x00-\x7F])/g, '$1');
      for (const [a, b] of OCR_FIX) line = line.replace(a, b);
      // 1行に複数料理: 、／,・2つ以上の空白で区切る
      for (let part of line.split(/[\/、,]+|\s{2,}/)) {
        part = part.replace(/\(?\d+(\.\d+)?\s*(kcal|g|円)\)?/gi, '').trim();
        if (part.length < 2 || part.length > 20 || NOT_DISH.test(part)) continue;
        if (!/[ぁ-んァ-ン一-龥]/.test(part)) continue;
        const r = analyzeDish(part);
        if (r.matched || r.fromName.length) out.push(r);
      }
    }
    return out;
  }
